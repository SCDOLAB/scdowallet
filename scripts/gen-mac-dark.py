#!/usr/bin/env python3
# Generates src/css/mac-native-dark.css: macOS dark appearance for html.mac-native.
# Every rule in the shared stylesheets that hard-codes a light-theme text or surface colour gets a dark twin,
# so new light rules stay covered when this script is re-run. Run: python3 scripts/gen-mac-dark.py
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
SRC = ['src/css/app112.css', 'src/css/shell310.css', 'src/css/mining201.css']
TEXT = {'#1c1c1e': 'var(--mn-text)', '#1b1d33': 'var(--mn-text)', '#1d1d1f': 'var(--mn-text)', '#3d4160': 'var(--mn-text2)', '#3a3a3c': 'var(--mn-text2)',
        '#3c3c43': 'var(--mn-text2)', '#2a2f63': 'var(--mn-text)', '#5f6482': 'var(--mn-text2)', '#6b6b70': 'var(--mn-text2)', '#4a4e6a': 'var(--mn-text2)', '#333': 'var(--mn-text)', '#222': 'var(--mn-text)'}
BG = {'#fff': 'var(--mn-surface)', '#ffffff': 'var(--mn-surface)', '#f2f2f7': 'var(--mn-bg)', '#e8f5e9': 'var(--mn-accent-soft)', '#f5f5f7': 'var(--mn-bg)', '#fafafa': 'var(--mn-surface)', '#f7f7fa': 'var(--mn-surface)'}
BORDER = {'#e5e5ea': 'var(--mn-line)', '#cfd3ea': 'var(--mn-ctl-line)', '#c9cde0': 'var(--mn-ctl-line)', '#eee': 'var(--mn-line)', '#e0e0e0': 'var(--mn-line)'}
out = []
for f in SRC:
    css = re.sub(r'/\*.*?\*/', '', (root / f).read_text(encoding='utf-8'), flags=re.S)
    for sel, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', css):
        sel = sel.strip()
        if not sel or sel in ('body', 'html, body', 'body:has(#app.shell)', '*') or sel.startswith(('from', 'to', '0%', '100%')) or re.match(r'^[\d.]+%', sel):
            continue
        decl = []
        for prop, val in re.findall(r'(?:^|;)\s*([a-z-]+)\s*:\s*([^;]+)', body):
            v = val.strip().lower().replace('!important', '').strip()
            if prop == 'color' and v in TEXT: decl.append('color: ' + TEXT[v])
            elif prop in ('background', 'background-color') and v in BG: decl.append('background: ' + BG[v])
            elif prop.startswith('border') and prop.endswith(('border', 'top', 'bottom', 'left', 'right', 'color')):
                for k, d in BORDER.items():
                    if k in v: decl.append(prop + ': ' + v.replace(k, d)); break
        if decl:
            sels = ', '.join('html.mac-native ' + s.strip() for s in sel.split(',') if s.strip() and not s.strip().startswith(('html', ':root')))
            if sels: out.append('  ' + sels + ' { ' + '; '.join(decl) + '; }')
head = '/* GENERATED by scripts/gen-mac-dark.py - macOS dark appearance (prefers-color-scheme: dark) for html.mac-native. */\n'
(root / 'src/css/mac-native-dark.css').write_text(head + '@media (prefers-color-scheme: dark) {\n' + '\n'.join(out) + '\n}\n', encoding='utf-8')
print(len(out), 'rules')
