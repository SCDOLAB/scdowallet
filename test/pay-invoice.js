// Pay invoice phase 1: TON + EIP-681 parsers, exact amounts, hand-off links.
'use strict'
const assert = require('assert')
const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8')
const P = require('../src/js/payInvoice/screen')
const E = require('../src/js/payInvoice/evm681')
const AMT = require('../src/js/amount')

const USDC = '0x833589fcd6edb6e08f4c7c32d4f71b54bda02913'
const CAT = '0x5b5f291722777c47c9bbb66b5ae05a8b455cfe21'
const RAW = '0:' + 'ab'.repeat(32)

function pad (x) { return String(x).replace(/^0x/i, '').toLowerCase().padStart(64, '0') }

// Same two lines as the live stake-wheel builder (cat-tip.js v2).
const wheelData = '0xa9059cbb' + pad(CAT) + pad(2006602n.toString(16))
assert.strictEqual(E.erc20TransferData(CAT, 2006602n), wheelData)
assert.strictEqual(E.erc20TransferData(CAT, '2006602'), wheelData)

const uri = 'ethereum:' + USDC + '@8453/transfer?address=' + CAT + '&uint256=2006602'
assert.strictEqual(E.buildEip681(USDC, 8453, CAT, 2006602n), uri)
assert.strictEqual(E.buildEip681(E.checksumAddress(USDC.slice(2)), '8453', E.checksumAddress(CAT.slice(2)), 2006602), uri)

const usdc = P.parseInvoice(uri)
assert.strictEqual(usdc.ok, true)
assert.strictEqual(usdc.invoice.atomic, 2006602n)
assert.strictEqual(usdc.invoice.display, '2.006602')
assert.strictEqual(usdc.invoice.amountText, '2.006602 USDC')
assert.strictEqual(usdc.invoice.memoText, 'No memo')
assert.strictEqual(usdc.invoice.network, 'Base')
assert.strictEqual(usdc.invoice.token, 'USDC')
assert.strictEqual(usdc.invoice.data, wheelData)
assert.strictEqual(usdc.invoice.uri, uri)
assert.strictEqual(P.parseInvoice(usdc.invoice.uri).invoice.uri, uri)

const sci = P.parseInvoice(uri.replace('uint256=2006602', 'uint256=2.006602e6'))
assert.strictEqual(sci.ok, true)
assert.strictEqual(sci.invoice.atomic, 2006602n)
assert.strictEqual(sci.invoice.display, '2.006602')
assert.strictEqual(sci.invoice.uri, uri)
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=2.006602e%2B6')).invoice.atomic, 2006602n)
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=2.0')).invoice.atomic, 2n)
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=1.5')).code, 'NOT_INTEGER')
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=2.0066021e6')).code, 'NOT_INTEGER')
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=-1')).code, 'NEGATIVE')
assert.strictEqual(P.parseInvoice(uri + '&value=0').code, 'VALUE_NOT_ALLOWED')
assert.strictEqual(P.parseInvoice(uri.replace('/transfer?', '/approve?')).code, 'WRONG_FUNCTION')
assert.strictEqual(P.parseInvoice(uri.replace('&uint256=2006602', '')).code, 'MISSING')
assert.strictEqual(P.parseInvoice(uri.replace(USDC, '0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02912')).code, 'BAD_CHECKSUM')
assert.strictEqual(P.parseInvoice(uri.replace(USDC, E.checksumAddress(USDC.slice(2)))).invoice.uri, uri)

const huge = '1' + '0'.repeat(80)
assert.strictEqual(P.parseInvoice(uri.replace('uint256=2006602', 'uint256=' + huge)).code, 'OVERFLOW')

const ton = P.buildTon({ address: RAW, amount: 1000000000n, memo: 'hello world', exp: 2000000000n })
const native = P.parseInvoice(ton)
assert.strictEqual(native.ok, true)
assert.strictEqual(native.invoice.atomic, 1000000000n)
assert.strictEqual(native.invoice.display, '1')
assert.strictEqual(native.invoice.token, 'TON')
assert.strictEqual(native.invoice.memo, 'hello world')
assert.strictEqual(native.invoice.uri, ton)
assert.strictEqual(native.invoice.expired(1999999999n), false)
assert.strictEqual(native.invoice.expired(2000000000n), true)
assert.strictEqual(P.parseInvoice(native.invoice.uri).invoice.uri, ton)

const noMemo = P.parseInvoice(P.buildTon({ address: RAW, amount: 1n }))
assert.strictEqual(noMemo.invoice.memo, null)
assert.strictEqual(noMemo.invoice.memoText, 'No memo')
assert.strictEqual(noMemo.invoice.display, '0.000000001')
assert.strictEqual(noMemo.invoice.expired(9999999999n), false)

const usdtUri = P.buildTon({ address: P.USDT_MASTER, amount: 1000000n, jetton: P.USDT_MASTER })
const usdt = P.parseInvoice(usdtUri)
assert.strictEqual(usdt.ok, true)
assert.strictEqual(usdt.invoice.atomic, 1000000n)
assert.strictEqual(usdt.invoice.display, '1')
assert.strictEqual(usdt.invoice.amountText, '1 USDT')
assert.strictEqual(usdt.invoice.token, 'USDT')
assert.strictEqual(usdt.invoice.memoText, 'No memo')
assert.strictEqual(usdt.invoice.uri, usdtUri)

const master = 'EQ' + 'A'.repeat(46)
const unknown = P.parseInvoice(P.buildTon({ address: RAW, amount: 5n, jetton: master }))
assert.strictEqual(unknown.ok, true)
assert.strictEqual(unknown.invoice.token, 'Unknown token')
assert.strictEqual(unknown.invoice.tokenAddress, master)
assert.strictEqual(unknown.invoice.decimals, null)
assert.strictEqual(unknown.invoice.display, '5')
assert.ok(P.reviewHtml(unknown.invoice, { differs: false }, 0n).includes('Unknown token ' + master))

assert.strictEqual(P.parseInvoice(ton.replace('amount=1000000000', 'amount=-5')).code, 'NEGATIVE')
assert.strictEqual(P.parseInvoice(ton.replace('amount=1000000000', 'amount=1.5')).code, 'NOT_INTEGER')
assert.strictEqual(P.parseInvoice(ton.replace(RAW, 'not-an-address')).code, 'BAD_ADDRESS')
assert.strictEqual(P.parseInvoice('ton://transfer/' + RAW).code, 'MISSING')
assert.strictEqual(P.tonAddress('-1:' + 'ab'.repeat(32)), null)
assert.strictEqual(P.tonAddress(RAW), RAW)

// toUnits cuts extra decimals. The invoice form must refuse that instead.
assert.strictEqual(AMT.toUnits('1.0000009', 6), 1000000n)
const cut = P.decimalToAtomic('1.0000009', 6)
assert.strictEqual(cut.ok, false)
assert.strictEqual(cut.code, 'TOO_MANY_DECIMALS')
assert.strictEqual(cut.wouldCutAtomic, 1000000n)
assert.strictEqual(cut.dropsValue, true)
assert.strictEqual(P.decimalToAtomic('2.006602', 6).atomic, 2006602n)
assert.strictEqual(P.invoiceFromManual({ network: 'base', token: 'USDC', to: CAT, amount: '2.006602' }).invoice.uri, uri)
assert.strictEqual(P.invoiceFromManual({ network: 'base', token: 'USDC', to: CAT, amount: '2.0066021' }).code, 'TOO_MANY_DECIMALS')

// Invoice 1 USDT, payer minimum 2: sending 2 is not paying 1.
const min = P.compareSend({ invoiceAtomic: 1000000n, decimals: 6, symbol: 'USDT', payerMinimum: '2' })
assert.strictEqual(min.differs, true)
assert.strictEqual(min.matchesInvoice, false)
assert.strictEqual(min.wouldSendAtomic, 2000000n)
assert.notStrictEqual(min.wouldSendAtomic, min.invoiceAtomic)
assert.strictEqual(min.text, 'Amount differs: invoice asks 1 USDT, this would send 2 USDT')
assert.strictEqual(min.allowSilentLess, false)
const review = P.reviewHtml(usdt.invoice, min, 0n)
assert.ok(review.includes('Amount differs: invoice asks 1 USDT, this would send 2 USDT'))
assert.ok(review.includes('id="payInvConfirm"'))
const handMin = P.handoffHtml(usdt.invoice, min, 0n, {})
assert.ok(handMin.includes('amount=1000000'))
assert.ok(!handMin.includes('amount=2000000'))
assert.ok(handMin.includes(min.text))

// A fee taken from the amount would send less. That must not be a silent payment.
const less = P.compareSend({ invoiceAtomic: 1000000n, decimals: 6, symbol: 'USDT', feeFromAmountAtomic: 1n })
assert.strictEqual(less.less, true)
assert.strictEqual(less.matchesInvoice, false)
assert.strictEqual(less.allowSilentLess, false)
assert.strictEqual(less.wouldSendAtomic, 999999n)
assert.ok(less.text.startsWith('Amount differs:'))
const handLess = P.handoffHtml(usdt.invoice, less, 1n, {})
assert.ok(handLess.includes('amount=1000000'))
assert.ok(!handLess.includes('amount=999999'))

const cutDiff = P.compareSend({ invoiceAtomic: 1000000n, decimals: 6, symbol: 'USDT', typedText: '1.0000009' })
assert.strictEqual(cutDiff.cutDrops, true)
assert.strictEqual(cutDiff.matchesInvoice, false)
assert.strictEqual(cutDiff.allowSilentLess, false)
assert.strictEqual(cutDiff.text, 'Amount differs: invoice asks 1.0000009 USDT, this would send 1 USDT')

const expired = P.parseInvoice(P.buildTon({ address: RAW, amount: 1n, exp: 10n }))
const blocked = P.handoffHtml(expired.invoice, { differs: false, text: '' }, 10n, {})
