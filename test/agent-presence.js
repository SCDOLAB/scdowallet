// Closing the window keeps the agent online. Quit asks once, and the lines can be overridden.
'use strict'
const assert = require('assert')
const fs = require('fs')
const path = require('path')
const vm = require('vm')

const root = path.join(__dirname, '..')
const main = fs.readFileSync(path.join(root, 'main.js'), 'utf8')
const app = fs.readFileSync(path.join(root, 'src/js/app112.js'), 'utf8')
const preload = fs.readFileSync(path.join(root, 'preload.js'), 'utf8')
const tray = fs.readFileSync(path.join(root, 'src/main/trayStatus.js'), 'utf8')

const box = { window: {} }
vm.runInNewContext(fs.readFileSync(path.join(root, 'src/js/i18n112.js'), 'utf8'), box)
const EN = box.window.I18N112.EN
const CN = box.window.I18N112.CN
assert.strictEqual(EN.agentStayOpen, 'Your agent is online only while SCDO Wallet is running. Keep it open or in the tray.')
assert.strictEqual(EN.agentOnlineLine, 'Online · keep app running')
assert.strictEqual(EN.agentOfflineLine, 'Offline · goes online when the wallet is open')
assert.strictEqual(EN.trayStayNotice, 'SCDO Wallet is still running in the tray so your agent stays online. Quit from the tray menu to stop.')
assert.strictEqual(EN.quitAgentMsg, 'Quitting takes your agent offline and pauses rewards.')
assert.strictEqual(EN.quitAgentQuit, 'Quit')
assert.strictEqual(EN.quitAgentStay, 'Keep running')
assert.strictEqual(EN.quitAgentDontAsk, "Don't ask again")
assert.strictEqual(CN.agentStayOpen, 'Agent 只在 SCDO Wallet 執行時在線。請保持開啟，或留在系統匣。')
assert.strictEqual(CN.agentOnlineLine, '在線·請保持程式執行')
assert.strictEqual(CN.agentOfflineLine, '離線·開啟錢包後自動上線')
assert.strictEqual(CN.agentX402Pending, '待生成（Agent 上線後自動分配）')
assert.strictEqual(EN.agentX402Pending, 'Not yet assigned (assigned when the agent goes online)')
assert.ok(main.includes('getAgentOnline: () => agentLedgerOnline()'))
assert.strictEqual(CN.trayStayNotice, 'SCDO Wallet 仍在系統匣執行，Agent 才會保持在線。要停止請從系統匣選單結束。')
assert.strictEqual(CN.quitAgentMsg, '結束後 Agent 會離線，獎勵也會暫停。')
assert.strictEqual(CN.quitAgentQuit, '結束')
assert.strictEqual(CN.quitAgentStay, '繼續執行')
assert.strictEqual(CN.quitAgentDontAsk, '不要再問')
assert.strictEqual(EN.loginToggle, 'Launch at login (start minimised in tray)')
const fresh = EN.agentStayOpen + EN.agentOnlineLine + EN.agentOfflineLine + EN.trayStayNotice + EN.quitAgentMsg + CN.agentStayOpen + CN.trayStayNotice + CN.quitAgentMsg
assert.ok(!/mining|GPU|CPU|算力/.test(fresh))

const quit = main.slice(main.indexOf('async function requestQuit'), main.indexOf('function gracefulQuit'))
assert.ok(quit.indexOf('afterQuit') >= 0 && quit.indexOf('afterQuit') < quit.indexOf('clearPageRunFlags'))
assert.ok(quit.indexOf('confirmAgentQuit') >= 0 && quit.indexOf('confirmAgentQuit') < quit.indexOf('afterQuit'))
assert.ok(quit.includes('confirm && agentProcessOnline()'))
assert.ok(quit.includes('confirm && miningNow()'))
const ask = main.slice(main.indexOf('function confirmAgentQuit'), main.indexOf('let startHidden'))
assert.ok(ask.includes('defaultId: 1') && ask.includes('cancelId: 1'))
const decide = ask.slice(ask.indexOf('return box.then'))
assert.ok(decide.indexOf('response !== 0') < decide.indexOf('r.checkboxChecked'))
assert.ok(decide.includes('writeIntent({ agentQuitQuiet: true })'))
assert.ok(ask.indexOf('agentQuitQuiet === true') < ask.indexOf('showMessageBox'))
assert.ok(ask.includes("uiString('quitAgentMsg'"))
assert.ok(main.includes('function noteHiddenToTray'))
assert.ok(main.includes('hintShown = true'))
assert.ok(main.includes('noteHiddenToTray()'))
assert.ok(main.includes('sendTrayHint()'))
assert.ok(main.includes("reason: 'update'") && main.includes("reason: 'installer'"))
assert.ok(main.includes('trayHintDismissed = true'))
assert.ok(!main.includes('openAtLogin: true'))

assert.ok(app.includes('id="agentStayOpen"') || app.includes('firstRunHtml'))
assert.ok(app.includes('data-act="trayHintDismiss"'))
assert.ok(app.includes('trayHintHtml()'))
assert.ok(app.includes("api.on('agent:trayHint'"))
assert.ok(preload.includes("'session:trayHintDismiss'") && preload.includes("'agent:trayHint'"))
assert.ok(tray.includes('presenceItem') && tray.includes('agentOnlineLine') && tray.includes('agentOfflineLine'))
assert.ok(tray.includes('Launch at login (start minimised in tray)'))

console.log('agent-presence: ok')
